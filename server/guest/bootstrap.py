# Provider API readiness precedes Xorg and can precede its final driver restart.
# A screen-ready daemon must be stable before creating our MCP transport. A
# restored service can also remain active after its runtime socket disappeared:
# systemd then has nothing to restart and every later bootstrap waits on a path
# that can never return. Once X itself answers and the daemon has been stable
# for five seconds, repair that exact state once. Human control prevents this
# script from running, so it cannot interrupt somebody holding the screen.
def wait_for_provider_driver(seconds=12):
 deadline=time.monotonic()+seconds;repaired=False
 while time.monotonic()<deadline:
  stable=x_ready=driver_socket=False
  try:
   raw=subprocess.check_output(['systemctl','--user','show','cua-driver.service','-p','ActiveState','-p','ActiveEnterTimestampMonotonic'],env=env,timeout=2,text=True)
   state=dict(line.split('=',1) for line in raw.splitlines() if '=' in line)
   age=time.monotonic()-int(state.get('ActiveEnterTimestampMonotonic','0'))/1000000
   stable=state.get('ActiveState')=='active' and age>=5
   driver_socket=pathlib.Path('/run/ascii-cua/driver.sock').exists()
   subprocess.run(['xset','q'],env={**env,'XAUTHORITY':str(pathlib.Path.home()/'.Xauthority')},check=True,timeout=2,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
   x_ready=True
  except (OSError,ValueError,subprocess.SubprocessError):pass
  if stable and driver_socket and x_ready:return True
  if stable and x_ready and not driver_socket and not repaired:
   subprocess.run(['systemctl','--user','restart','--no-block','cua-driver.service'],env=env,check=True,timeout=5,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
   repaired=True
  time.sleep(.5)
 return False
