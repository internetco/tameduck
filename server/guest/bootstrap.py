# Ten seconds was not enough. This waits on two separate things - our own
# controls answering a ping, and the provider's driver socket existing - and on
# a machine that has just booted, or a busy one, either can still be coming up.
# Somebody who pressed Take control a moment after starting a computer got
# "The computer action could not finish", with nothing said about what was slow,
# and the fix was to try again later. Wait long enough to cover a cold start,
# and say which half was missing when it really does not arrive.
ours=theirs=False
# Shorter than the budget the host gives this whole script, deliberately, and
# the two must stay that way round. It was the same 45 seconds as the host's,
# so the moment this gave up was the moment the host stopped listening: the
# message below - the only one that says which half of the desktop failed to
# start - could never once be delivered, and every failure here arrived as a
# bare timeout instead. tests/computer-stop.test.mjs holds the two numbers to
# their order.
deadline=time.monotonic()+30
# The provider's daemon can lose its socket and keep running (see driver.py).
# Waiting out the thirty seconds for a file that was not coming back failed the
# setup of new computers on the provider's image of 23 September; restarting
# the daemon brings it back.
missing=None;repairs=0
while time.monotonic()<deadline:
 try:
  with socket.socket(socket.AF_UNIX) as s:
   s.settimeout(.5);s.connect(str(base/'control.sock'));s.sendall(b'{"ping":true}\n');assert b'ready' in s.recv(100)
  ours=True
 except (OSError,AssertionError):ours=False
 theirs=pathlib.Path('/run/ascii-cua/driver.sock').exists()
 if ours and theirs:break
